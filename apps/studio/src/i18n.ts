export type Lang = 'ar' | 'en';

export const STRINGS: Record<Lang, Record<Key, string>> = { ar, en };

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  let s = STRINGS[lang][key];
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** The page's first language: the saved choice, else the browser's (Arabic unless it prefers English). */
export function initialLang(saved: string | null, browserLanguages: readonly string[]): Lang {
  if (saved === 'ar' || saved === 'en') return saved;
  const first = browserLanguages.find((l) => /^(ar|en)\b/i.test(l));
  return first && /^en/i.test(first) ? 'en' : 'ar';
}

#!/usr/bin/env node
// Generates src/modules/users/data/confusables.generated.ts from the vendored Unicode
// confusables.txt (UTS #39). Run: node scripts/generate-confusables.mjs
// The output is ASCII-only: "SRC>TGT TGT;" records with hex code points.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src/modules/users/data');

export function buildConfusablesModule(text) {
  const sha256 = createHash('sha256').update(text).digest('hex');
  const version = /^# Version: (\S+)/m.exec(text)?.[1] ?? 'unknown';
  const records = [];
  for (const line of text.split('\n')) {
    const body = line.split('#')[0]?.trim();
    if (!body) continue;
    const [source, target, type] = body.split(';').map((field) => field.trim());
    if (!source || !target || type !== 'MA') continue;
    records.push(`${source}>${target}`);
  }
  return [
    '/* eslint-disable */',
    '// GENERATED by scripts/generate-confusables.mjs from data/confusables.txt — do not edit.',
    `// Unicode confusables.txt version ${version}, sha256 ${sha256}, ${records.length} mappings.`,
    `export const CONFUSABLES_SOURCE_SHA256 = '${sha256}';`,
    `export const CONFUSABLES_VERSION = '${version}';`,
    `export const CONFUSABLES_DATA =`,
    `  '${records.join(';')}';`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = readFileSync(join(dataDir, 'confusables.txt'), 'utf8');
  writeFileSync(join(dataDir, 'confusables.generated.ts'), buildConfusablesModule(text));
  process.stdout.write('wrote src/modules/users/data/confusables.generated.ts\n');
}

#!/usr/bin/env node
// Generates src/modules/countries/data/countries.generated.ts from the vendored data
// (CONVENTIONS §11.7, contract v1.4):
//  - data/iso3166-1-alpha2.txt: the 249 officially assigned ISO 3166-1 alpha-2 codes;
//  - data/cldr-48.0.0/{ar,en}/territories.json: Unicode CLDR 48 (npm cldr-localenames-full
//    48.0.0), unmodified. The default name of each code is used (never `-alt-short` /
//    `-alt-variant`); no overrides exist in v1.4.
// The build fails when a code has no non-empty name in either locale (the contract's build-time
// check). Run: node scripts/generate-countries.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src/modules/countries/data');

export const COUNTRY_SOURCE_FILES = [
  'iso3166-1-alpha2.txt',
  'cldr-48.0.0/ar/territories.json',
  'cldr-48.0.0/en/territories.json',
];

/** openapi `Country.name` maxLength. */
const MAX_NAME_LENGTH = 80;

export function sha256(text) {
  return createHash('sha256').update(text).digest('hex');
}

export function parseCodes(text) {
  const codes = text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line !== '' && !line.startsWith('#'));
  for (const code of codes) {
    if (!/^[A-Z]{2}$/.test(code)) throw new Error(`invalid ISO 3166-1 alpha-2 code "${code}"`);
  }
  if (new Set(codes).size !== codes.length) throw new Error('duplicate country code');
  return codes;
}

function territories(text, locale) {
  const json = JSON.parse(text);
  const names = json?.main?.[locale]?.localeDisplayNames?.territories;
  if (!names || typeof names !== 'object') throw new Error(`no territories for ${locale}`);
  return names;
}

function quote(text) {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** `files` maps each name of COUNTRY_SOURCE_FILES to its text. */
export function buildCountriesModule(files) {
  const codes = parseCodes(files['iso3166-1-alpha2.txt']);
  const ar = territories(files['cldr-48.0.0/ar/territories.json'], 'ar');
  const en = territories(files['cldr-48.0.0/en/territories.json'], 'en');
  const rows = codes.map((code) => {
    const nameEn = en[code];
    const nameAr = ar[code];
    for (const [locale, name] of [
      ['en', nameEn],
      ['ar', nameAr],
    ]) {
      if (typeof name !== 'string' || name.trim() === '') {
        throw new Error(`country ${code} has no ${locale} name in CLDR 48`);
      }
      if ([...name].length > MAX_NAME_LENGTH) throw new Error(`country ${code} ${locale} name too long`);
    }
    return `  [${quote(code)}, ${quote(nameEn)}, ${quote(nameAr)}],`;
  });
  const hashes = COUNTRY_SOURCE_FILES.map((name) => `  ${quote(name)}: ${quote(sha256(files[name]))},`);
  return [
    '/* eslint-disable */',
    '// GENERATED by scripts/generate-countries.mjs from data/iso3166-1-alpha2.txt and',
    '// data/cldr-48.0.0/*/territories.json; do not edit. CONVENTIONS section 11.7 (contract v1.4).',
    "export const CLDR_VERSION = '48.0.0';",
    'export const COUNTRY_SOURCE_SHA256: Readonly<Record<string, string>> = {',
    ...hashes,
    '};',
    `/** [code, English name, Arabic name] for the ${rows.length} selectable countries, by code. */`,
    'export const COUNTRY_DATA: readonly (readonly [string, string, string])[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}

export function readCountrySources(dir = dataDir) {
  return Object.fromEntries(
    COUNTRY_SOURCE_FILES.map((name) => [name, readFileSync(join(dir, name), 'utf8')]),
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(dataDir, 'countries.generated.ts'), buildCountriesModule(readCountrySources()));
  process.stdout.write('wrote src/modules/countries/data/countries.generated.ts\n');
}

-- v1.50-live (D229, CONVENTIONS §10.80; owner 2026-11-01): «PK أحكام» — a PK type DARES next to the normal PK: after a
-- decisive result the server draws one of three dares (one easy, one medium, one hard) for the loser, who accepts or
-- refuses; accepted, a 3-minute timer runs and the winner judges «نُفّذ» / «لم يُنفّذ». New per-host PK points (win
-- / draw / loss / refused dare, values in `pk_dare_settings`), the dare library (`pk_dares`, seeded by the
-- `pk-dares-admin import` CLI on deploy, not here: 20 000 rows), viewer reports and a compact per-host history of the
-- dares seen (a bitmap over `pk_dares.seq_no`). The runtime role gets DML through the default privileges
-- (20261016130000_per_database_runtime_group): no GRANT. Existing matches, invitations and waits are NORMAL.

-- CreateEnum
CREATE TYPE "pk_type" AS ENUM ('NORMAL', 'DARES');
CREATE TYPE "pk_dare_category" AS ENUM ('FUNNY', 'SINGING', 'ACTING', 'TALK', 'TRUTH', 'DANCE_LIGHT', 'IMITATION', 'QUIZ', 'DRAWING');
CREATE TYPE "pk_dare_level" AS ENUM ('EASY', 'MEDIUM', 'HARD');
CREATE TYPE "pk_dare_status" AS ENUM ('DECIDING', 'ACTIVE', 'DONE', 'REFUSED', 'CANCELLED');
CREATE TYPE "pk_dare_cause" AS ENUM ('LOSER_REFUSED', 'DECIDE_TIMEOUT', 'LOSER_LEFT', 'WINNER_DONE', 'WINNER_NOT_DONE', 'TIMER', 'WINNER_LEFT', 'ADMIN');

-- The PK type of a match, an invitation and a random wait (a DARES waiter is only paired with another DARES waiter).
ALTER TABLE "pk_matches" ADD COLUMN "type" "pk_type" NOT NULL DEFAULT 'NORMAL';
ALTER TABLE "pk_invites" ADD COLUMN "type" "pk_type" NOT NULL DEFAULT 'NORMAL';
ALTER TABLE "pk_queue" ADD COLUMN "type" "pk_type" NOT NULL DEFAULT 'NORMAL';

-- The PK points record (owner: win +3, draw +1, loss 0, refused dare −3; may go below 0).
ALTER TABLE "pk_host_records" ADD COLUMN "points" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "pk_host_records" ADD COLUMN "dares_done" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "pk_host_records" ADD COLUMN "dares_refused" INTEGER NOT NULL DEFAULT 0;

-- The dare library.
CREATE TABLE "pk_dares" (
    "id" UUID NOT NULL,
    "seq_no" INTEGER GENERATED BY DEFAULT AS IDENTITY,
    "code" VARCHAR(40) NOT NULL,
    "text_ar" VARCHAR(200) NOT NULL,
    "text_en" VARCHAR(300) NOT NULL,
    "category" "pk_dare_category" NOT NULL,
    "level" "pk_dare_level" NOT NULL,
    "requires_camera" BOOLEAN NOT NULL DEFAULT true,
    "active" BOOLEAN NOT NULL DEFAULT true,
    "disabled_reason" VARCHAR(16),
    "report_count" INTEGER NOT NULL DEFAULT 0,
    "reports_cleared_at" TIMESTAMPTZ(3),
    "created_by" VARCHAR(8) NOT NULL DEFAULT 'SEED',
    "created_by_id" UUID,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "pk_dares_pkey" PRIMARY KEY ("id")
);
ALTER TABLE "pk_dares" ADD CONSTRAINT "pk_dares_shape" CHECK (
  created_by IN ('SEED', 'ADMIN') AND report_count >= 0 AND seq_no BETWEEN 1 AND 1000000
  AND (disabled_reason IS NULL OR disabled_reason IN ('ADMIN', 'REPORTS')));
CREATE UNIQUE INDEX "pk_dares_code_key" ON "pk_dares"("code");
CREATE UNIQUE INDEX "pk_dares_seq_no_key" ON "pk_dares"("seq_no");
CREATE INDEX "pk_dares_draw_idx" ON "pk_dares"("level") WHERE active;
CREATE INDEX "pk_dares_reported_idx" ON "pk_dares"("report_count" DESC) WHERE report_count > 0;

-- The dare of one DARES match (one row; created when the battle ends with a winner).
CREATE TABLE "pk_match_dares" (
    "match_id" UUID NOT NULL,
    "loser_side" "pk_side" NOT NULL,
    "loser_host_id" UUID NOT NULL,
    "winner_host_id" UUID NOT NULL,
    "option_ids" UUID[] NOT NULL,
    "drawn" SMALLINT NOT NULL,
    "dare_id" UUID NOT NULL,
    "status" "pk_dare_status" NOT NULL DEFAULT 'DECIDING',
    "cause" "pk_dare_cause",
    "reveal_at" TIMESTAMPTZ(3) NOT NULL,
    "decide_by" TIMESTAMPTZ(3) NOT NULL,
    "started_at" TIMESTAMPTZ(3),
    "ends_at" TIMESTAMPTZ(3),
    "finished_at" TIMESTAMPTZ(3),
    "points" INTEGER NOT NULL DEFAULT 0,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "pk_match_dares_pkey" PRIMARY KEY ("match_id")
);
ALTER TABLE "pk_match_dares" ADD CONSTRAINT "pk_match_dares_shape" CHECK (
  cardinality(option_ids) = 3 AND drawn BETWEEN 0 AND 2 AND option_ids[drawn + 1] = dare_id
  AND (status IN ('DECIDING', 'ACTIVE')) = (finished_at IS NULL)
  AND (status <> 'ACTIVE' OR (started_at IS NOT NULL AND ends_at IS NOT NULL)));
CREATE INDEX "pk_match_dares_open_idx" ON "pk_match_dares"("status") WHERE finished_at IS NULL;
CREATE INDEX "pk_match_dares_loser_idx" ON "pk_match_dares"("loser_host_id", "created_at" DESC);
ALTER TABLE "pk_match_dares" ADD CONSTRAINT "pk_match_dares_match_id_fkey" FOREIGN KEY ("match_id") REFERENCES "pk_matches"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "pk_match_dares" ADD CONSTRAINT "pk_match_dares_dare_id_fkey" FOREIGN KEY ("dare_id") REFERENCES "pk_dares"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- One report per person per dare.
CREATE TABLE "pk_dare_reports" (
    "dare_id" UUID NOT NULL,
    "user_id" UUID NOT NULL,
    "match_id" UUID,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "pk_dare_reports_pkey" PRIMARY KEY ("dare_id", "user_id")
);
CREATE INDEX "pk_dare_reports_user_idx" ON "pk_dare_reports"("user_id");
ALTER TABLE "pk_dare_reports" ADD CONSTRAINT "pk_dare_reports_dare_id_fkey" FOREIGN KEY ("dare_id") REFERENCES "pk_dares"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "pk_dare_reports" ADD CONSTRAINT "pk_dare_reports_user_id_fkey" FOREIGN KEY ("user_id") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- The dares a host has been shown (bit n = `pk_dares.seq_no` n), reset when every active dare was seen.
CREATE TABLE "pk_dare_seen" (
    "host_id" UUID NOT NULL,
    "bits" BYTEA NOT NULL,
    "seen" INTEGER NOT NULL DEFAULT 0,
    "cycles" INTEGER NOT NULL DEFAULT 0,
    "updated_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "pk_dare_seen_pkey" PRIMARY KEY ("host_id")
);
ALTER TABLE "pk_dare_seen" ADD CONSTRAINT "pk_dare_seen_host_id_fkey" FOREIGN KEY ("host_id") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- The PK points written per match and host (one row per kind: a retry never counts twice).
CREATE TABLE "pk_point_events" (
    "match_id" UUID NOT NULL,
    "host_id" UUID NOT NULL,
    "kind" VARCHAR(16) NOT NULL,
    "points" INTEGER NOT NULL,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "pk_point_events_pkey" PRIMARY KEY ("match_id", "host_id", "kind")
);
ALTER TABLE "pk_point_events" ADD CONSTRAINT "pk_point_events_kind" CHECK (kind IN ('WIN', 'DRAW', 'LOSS', 'DARE_REFUSED'));
CREATE INDEX "pk_point_events_host_idx" ON "pk_point_events"("host_id", "created_at" DESC);
ALTER TABLE "pk_point_events" ADD CONSTRAINT "pk_point_events_match_id_fkey" FOREIGN KEY ("match_id") REFERENCES "pk_matches"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "pk_point_events" ADD CONSTRAINT "pk_point_events_host_id_fkey" FOREIGN KEY ("host_id") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- One row (id 1): the PK points and the loser's decision time, edited in «أحكام PK» (OWNER / MODERATION, audited).
CREATE TABLE "pk_dare_settings" (
    "id" SMALLINT NOT NULL DEFAULT 1,
    "win_points" INTEGER NOT NULL DEFAULT 3,
    "draw_points" INTEGER NOT NULL DEFAULT 1,
    "loss_points" INTEGER NOT NULL DEFAULT 0,
    "refuse_points" INTEGER NOT NULL DEFAULT -3,
    "decide_seconds" INTEGER NOT NULL DEFAULT 30,
    "reports_to_disable" INTEGER NOT NULL DEFAULT 5,
    "updated_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_by_id" UUID,

    CONSTRAINT "pk_dare_settings_pkey" PRIMARY KEY ("id")
);
ALTER TABLE "pk_dare_settings" ADD CONSTRAINT "pk_dare_settings_shape" CHECK (
  id = 1 AND win_points BETWEEN -100 AND 100 AND draw_points BETWEEN -100 AND 100 AND loss_points BETWEEN -100 AND 100
  AND refuse_points BETWEEN -100 AND 100 AND decide_seconds BETWEEN 5 AND 300 AND reports_to_disable BETWEEN 1 AND 1000);
